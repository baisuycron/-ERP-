function writeTable(sheet, startCell, rows, tableName) {
  sheet.getRange(startCell).writeValues(rows);
  const rowCount = rows.length;
  const colCount = Math.max(...rows.map((r) => r.length));
  const startCol = startCell.match(/[A-Z]+/)[0];
  const startRow = Number(startCell.match(/\d+/)[0]);
  function colName(n) {
    let s = "";
    while (n >= 0) {
      s = String.fromCharCode((n % 26) + 65) + s;
      n = Math.floor(n / 26) - 1;
    }
    return s;
  }
  const startIndex = startCol.charCodeAt(0) - 65;
  const endCol = colName(startIndex + colCount - 1);
  const range = `${startCol}${startRow}:${endCol}${startRow + rowCount - 1}`;
  const table = sheet.tables.add(range, true, tableName);
  table.style = "TableStyleMedium2";
  table.showFilterButton = true;
  return range;
}

