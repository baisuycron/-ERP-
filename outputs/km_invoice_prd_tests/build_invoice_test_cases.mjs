const cases = [];
const counters = {};
function tc(prefix, module, client, feature, title, precondition, steps, data, expected, priority = "P1", type = "功能", source = "KM PRD 图文理解") {
  counters[prefix] = (counters[prefix] || 0) + 1;
  cases.push({
    id: `${prefix}-${String(counters[prefix]).padStart(3, "0")}`,
    module,
    client,
    feature,
    title,
    precondition,
    steps,
    data,
    expected,
    priority,
    type,
    status: "未执行",
    source,
  });
}

function steps(...items) {
  return items.map((item, index) => `${index + 1}. ${item}`).join("\n");
}

function expected(...items) {
  return items.map((item) => `- ${item}`).join("\n");
}

