const cases = [];
const counters = {};

function lines(...items) {
  return items.map((item, index) => `${index + 1}. ${item}`).join("\n");
}

function expects(...items) {
  return items.map((item) => `- ${item}`).join("\n");
}

function add(prefix, module, role, feature, title, precondition, stepText, data, expected, priority = "P1", type = "功能", source = "KM PRD-发票三期需求 图文理解") {
  counters[prefix] = (counters[prefix] || 0) + 1;
  cases.push({
    id: `${prefix}-${String(counters[prefix]).padStart(3, "0")}`,
    module,
    role,
    feature,
    title,
    precondition,
    steps: stepText,
    data,
    expected,
    priority,
    type,
    status: "未执行",
    source,
  });
}

